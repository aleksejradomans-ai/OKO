"""task_processor_config.py — конфигурация read-only доступа для
task_processor.py.

Отдельный модуль, не часть config.py — TaskProcessor сознательно изолирован
от основного config.py (см. историю решений: "не имеет доступа к реестру
проекта"). config.py читает TELEGRAM_TOKEN через _require_env и завершает
процесс при его отсутствии — TaskProcessor не должен зависеть от наличия
Telegram-токена просто чтобы прочитать список разрешённых директорий.
"""
from __future__ import annotations

from pathlib import Path

# Whitelist расширений для read-only доступа. Явно НЕ включены: .env,
# .json, .yaml, .yml, .ini — любой формат, где исторически хранятся секреты
# или конфигурация с чувствительными значениями. .py/.md/.txt — это код и
# документация, единственное, что TaskProcessor должен видеть для генерации
# релевантного контекста при составлении плана/черновика.
ALLOWED_EXTENSIONS = frozenset({".py", ".md", ".txt"})

# ВАЖНО (найдено при тестировании, не очевидно из кода): Path(".env").suffix
# возвращает '' (пустую строку), не '.env' — Python трактует файлы вида
# .name как "точечные файлы без расширения", не как файл с расширением
# ".env". Это означает .env/.gitignore и подобные dotfiles УЖЕ отклоняются
# текущим ALLOWED_EXTENSIONS (пустая строка не входит в множество), но не
# потому что они явно запрещены по имени — просто потому что не входят в
# whitelist. Если когда-нибудь понадобится разрешить файлы без расширения
# (например, "Makefile"), добавление "" в ALLOWED_EXTENSIONS ОТКРОЕТ доступ
# и к .env вместе с ними — это нужно будет переосмыслить отдельно, не
# добавлять "" не задумываясь.

# Явный whitelist директорий, не "всё кроме .git/.env". Белый список вместо
# чёрного по тому же принципу, что используется в path_guard.py: чёрный
# список неполон по определению (нельзя перечислить все чувствительные
# места), белый список даёт структурную гарантию — если директория не в
# этом списке, она недоступна, без необходимости угадывать, что ещё нужно
# запретить. Пути относительные — резолвятся относительно project_root,
# переданного в TaskProcessor при инициализации, не абсолютные константы
# здесь (TaskProcessor может быть запущен из разных мест).
ALLOWED_READ_DIRS = (Path("src"), Path("tests"))
