class ActionAxis:
    def resolve(self, found: dict, has_color: bool, negated: bool, all_actions=()) -> Coordinate:
        """found: действие -> True, если получено только нечётким сопоставлением."""
        values = dict(found)
        if negated:
            # «не включай свет» — не команда на включение: решает Оператор
            return Coordinate.ambiguous(all_actions)
        if has_color and len(values) > 1:
            values.pop("color", None)        # «включи красный цвет»: цвет — параметр включения
        if len(values) > 1:
            return Coordinate.ambiguous(sorted(values))
        if not values:
            # названный цвет сам является лексическим маркером действия color
            return Coordinate.resolved("color", SRC_BUILTIN) if has_color else Coordinate()
        (value, fuzzy), = values.items()
        return Coordinate.resolved(value, SRC_FUZZY, 0.8) if fuzzy else Coordinate.resolved(value, SRC_BUILTIN)
