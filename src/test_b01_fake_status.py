def test_module_reply_never_reaches_guard():
    """Честный ответ модуля ТВ приходит из _route_reply до защит process_logic -- правило его не видит."""
    from pathlib import Path
    text = (Path(__file__).resolve().parent / "bot.py").read_text(encoding="utf-8-sig")
    body = text[text.index("async def _route_reply"):text.index("async def _run_tv_route")]
    assert "fake_done" not in body and "fake_status" not in body
