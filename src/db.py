"""Единая точка создания соединений с SQLite-базой знаний.

Раньше bot.py и knowledge_indexer.py открывали раздельные sqlite3.connect()
ad hoc внутри каждой функции — это работало, потому что SQLite поддерживает
несколько читающих/пишущих соединений с разумным timeout, но создавало два
независимых места, знающих про DB_PATH и параметры подключения, которые
могли разойтись (например, один забыл timeout, другой использует другой).

Не вводит пул соединений или синглтон-объект — для текущего объёма
операций (один процесс бота, нечастые индексации) это было бы избыточным
усложнением. get_connection() — просто фабрика с единообразными параметрами,
вызывающий код сам управляет жизненным циклом (with-блок), как и раньше.

WAL-режим (journal_mode=WAL) включён явно при каждом открытии соединения.
Это стало необходимым после того, как knowledge_indexer.py начал писать
embedding-векторы в ту же базу, что читает/пишет bot.py — при записи из
двух независимых процессов без WAL растёт вероятность "database is locked"
даже при заданном timeout (timeout откладывает ошибку, не устраняет её
причину). WAL создаёт рядом с .db файлы -wal и -shm — это штатное поведение
SQLite, не мусор для очистки.
"""
from __future__ import annotations

import sqlite3

import config

DEFAULT_TIMEOUT_S = 10.0


def get_connection(timeout: float = DEFAULT_TIMEOUT_S) -> sqlite3.Connection:
    """Открывает соединение с config.DB_PATH с единообразным timeout и WAL.

    Не кэширует и не переиспользует соединение между вызовами — каждый
    вызов открывает новое. Вызывающий код обязан закрыть его сам (через
    `with` или явный `.close()`), как делал раньше с прямыми вызовами
    sqlite3.connect().
    """
    conn = sqlite3.connect(str(config.DB_PATH), timeout=timeout)
    conn.execute("PRAGMA journal_mode=WAL;")
    return conn
